const { Pool, types } = require('pg');
const seedEvents = require('./seed-events');

types.setTypeParser(1082, value => value);

const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  max: Number(process.env.PG_POOL_MAX) || 5,
  idleTimeoutMillis: 10000,
  connectionTimeoutMillis: 10000
});

async function initialize() {
  if (!process.env.DATABASE_URL) {
    throw new Error('Set DATABASE_URL to your hosted PostgreSQL connection string.');
  }

  await pool.query(`
    CREATE TABLE IF NOT EXISTS students (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      usn TEXT NOT NULL UNIQUE,
      email TEXT NOT NULL UNIQUE,
      department TEXT NOT NULL,
      password_hash TEXT NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE TABLE IF NOT EXISTS admins (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      email TEXT NOT NULL UNIQUE,
      password_hash TEXT NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE TABLE IF NOT EXISTS events (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      description TEXT NOT NULL,
      event_date DATE NOT NULL,
      event_time TEXT NOT NULL,
      venue TEXT NOT NULL,
      category TEXT NOT NULL CHECK (category IN ('Technical', 'Cultural', 'Sports', 'Workshops')),
      capacity INTEGER NOT NULL DEFAULT 50 CHECK (capacity > 0),
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE TABLE IF NOT EXISTS registrations (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      registration_id TEXT NOT NULL UNIQUE,
      student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
      event_id INTEGER NOT NULL REFERENCES events(id) ON DELETE CASCADE,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      UNIQUE (student_id, event_id)
    );
    CREATE TABLE IF NOT EXISTS user_sessions (
      sid VARCHAR NOT NULL PRIMARY KEY,
      sess JSON NOT NULL,
      expire TIMESTAMP(6) NOT NULL
    );
    CREATE INDEX IF NOT EXISTS user_sessions_expire_idx ON user_sessions (expire);
  `);

  await pool.query('ALTER TABLE events ADD COLUMN IF NOT EXISTS capacity INTEGER NOT NULL DEFAULT 50 CHECK (capacity > 0)');

  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await client.query('SELECT pg_advisory_xact_lock($1)', [739184205]);
    const { rows } = await client.query('SELECT COUNT(*) AS count FROM events');
    if (Number(rows[0].count) === 0) {
      for (const [name, description, daysAhead, venue, category, capacity] of seedEvents) {
        const date = new Date();
        date.setDate(date.getDate() + daysAhead);
        const eventDate = `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}-${String(date.getDate()).padStart(2, '0')}`;
        await client.query(
          'INSERT INTO events (name, description, event_date, event_time, venue, category, capacity) VALUES ($1, $2, $3, $4, $5, $6, $7)',
          [name, description, eventDate, '10:00', venue, category, capacity]
        );
      }
    }
    await client.query('COMMIT');
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
  }
}

async function execute(sql, params = []) {
  let parameterIndex = 0;
  const statement = sql.replace(/\?/g, () => `$${++parameterIndex}`);
  const isInsert = /^\s*INSERT\b/i.test(sql);
  try {
    const result = await pool.query(isInsert ? `${statement} RETURNING id` : statement, params);
    if (!isInsert && result.fields.length) return [result.rows];
    return [{
      insertId: result.rows[0]?.id ?? null,
      affectedRows: result.rowCount
    }];
  } catch (error) {
    if (error.code === '23505') error.code = 'SQLITE_CONSTRAINT_UNIQUE';
    throw error;
  }
}

async function registerForEvent(eventId, studentId, registrationId) {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const { rows } = await client.query(
      'SELECT id, capacity FROM events WHERE id = $1 AND event_date >= CURRENT_DATE FOR UPDATE',
      [eventId]
    );
    if (!rows.length) {
      const error = new Error('Event is no longer available.');
      error.code = 'EVENT_NOT_AVAILABLE';
      throw error;
    }
    const { rows: countRows } = await client.query(
      'SELECT COUNT(*) AS count FROM registrations WHERE event_id = $1',
      [eventId]
    );
    if (Number(countRows[0].count) >= rows[0].capacity) {
      const error = new Error('Event capacity reached.');
      error.code = 'EVENT_CAPACITY_REACHED';
      throw error;
    }
    await client.query(
      'INSERT INTO registrations (registration_id, student_id, event_id) VALUES ($1, $2, $3)',
      [registrationId, studentId, eventId]
    );
    await client.query('COMMIT');
  } catch (error) {
    await client.query('ROLLBACK');
    if (error.code === '23505') error.code = 'SQLITE_CONSTRAINT_UNIQUE';
    throw error;
  } finally {
    client.release();
  }
}

module.exports = {
  execute,
  query: execute,
  initialize,
  registerForEvent,
  isPostgres: true,
  pool
};
